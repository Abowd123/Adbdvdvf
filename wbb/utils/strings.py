def tr(key, lang=None, **kwargs):
    """Return the localized string for `key`, formatted with kwargs.

    Falls back to the DEFAULT_LANG table, then to the key itself, so a missing
    translation never crashes the bot.
    """
    lang = lang or DEFAULT_LANG
    table = STRINGS.get(lang) or STRINGS[DEFAULT_LANG]
    text = table.get(key)
    if text is None:
        text = STRINGS[DEFAULT_LANG].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text
